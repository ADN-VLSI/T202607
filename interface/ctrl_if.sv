interface ctrl_if;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // Signals
  //////////////////////////////////////////////////////////////////////////////////////////////////

  logic arst_n;
  logic clk;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // Variables
  //////////////////////////////////////////////////////////////////////////////////////////////////

  realtime tp = 10ns;

  bit internal_clk;
  bit clk_en;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // Sequentials
  //////////////////////////////////////////////////////////////////////////////////////////////////

  always begin
    realtime tp_local;
    tp_local = tp;
    #(tp_local / 2);
    internal_clk <= '1;
    #(tp_local / 2);
    internal_clk <= '0;
  end

  always begin
    @(posedge internal_clk);
    clk <= clk_en;
    @(negedge internal_clk);
    clk <= '0;
  end

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // Methods
  //////////////////////////////////////////////////////////////////////////////////////////////////

  function void set_clk_en(input bit en = 1);
    clk_en = en;
  endfunction

  task automatic start_clock(input real freq = 100_000_000);
    tp = 1s / freq;
    set_clk_en('1);
    @(posedge clk);
  endtask

  task automatic apply_reset(input realtime duration = 100ns,
                             input realtime pre_delay = duration / 10,
                             input realtime post_delay = pre_delay);
    #(pre_delay);
    arst_n <= '0;
    #(duration);
    arst_n <= '1;
    #(post_delay);
  endtask

endinterface
