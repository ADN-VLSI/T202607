module apb_uart_top_layered_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // IMPORTS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  import uart_regif_pkg::*;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  ctrl_if ctrl_intf ();

  apb_if apb_intf (
      .pclk(ctrl_intf.clk),
      .presetn(ctrl_intf.arst_n)
  );

  uart_if tx_intf ();
  uart_if rx_intf ();

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // VARIABLES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  integer pass_count;
  integer fail_count;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // RTL
  //////////////////////////////////////////////////////////////////////////////////////////////////

  apb_uart_top #(
      .ADDR_WIDTH  (32),
      .DATA_WIDTH  (32),
      .WSTRB_WIDTH (4),
      .FIFO_DEPTH_W(9)
  ) DUT (
      .clk_i    (ctrl_intf.clk),
      .arst_ni  (ctrl_intf.arst_n),
      .psel_i   (apb_intf.psel),
      .penable_i(apb_intf.penable),
      .paddr_i  (apb_intf.paddr),
      .pwrite_i (apb_intf.pwrite),
      .pwdata_i (apb_intf.pwdata),
      .pstrb_i  ('1),
      .pready_o (apb_intf.pready),
      .prdata_o (apb_intf.prdata),
      .pslverr_o(  /*LEFT BLANK*/),
      .tx_o     (tx_intf.line),
      .rx_i     (rx_intf.line),
      .intr_o   (  /*LEFT BLANK*/)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin

    automatic string test_name;
    automatic int    test_repeats;

    pass_count = 0;
    fail_count = 0;

    if (!$value$plusargs("CLI_TEST_NAME=%s", test_name)) test_name = "reset_test";
    if (!$value$plusargs("CLI_TEST_REPEATS=%d", test_repeats)) test_repeats = 1;

    $dumpfile("apb_uart_top_layered_tb.vcd");
    $timeformat(-9, 0, "ns");
    $dumpvars(0, apb_uart_top_layered_tb);

    ctrl_intf.apply_reset();
    ctrl_intf.start_clock();

    $display("APB UART LAYERED TESTBENCH - TEST: %s, REPEATS: %0d", test_name, test_repeats);

    case (test_name)

      default: begin
        $display("ERROR: Unknown test name '%s'", test_name);
      end

    endcase

    #100ns;

    $finish;
  end

endmodule
