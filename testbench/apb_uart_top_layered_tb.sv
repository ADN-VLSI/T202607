`include "ltb/obj/apb_seq_item.sv"
`include "ltb/obj/apb_rsp_item.sv"

`include "ltb/cmp/apb_driver.sv"
`include "ltb/cmp/apb_monitor.sv"

module apb_uart_top_layered_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // IMPORTS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  import uart_regif_pkg::ADDR_CTRL;
  import uart_regif_pkg::ADDR_CFG;
  import uart_regif_pkg::ADDR_STATUS;
  import uart_regif_pkg::ADDR_TXD;
  import uart_regif_pkg::ADDR_RXD;
  import uart_regif_pkg::ADDR_INTR;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  ctrl_if ctrl_intf ();

  apb_if apb_intf (
      .pclk(ctrl_intf.clk),
      .presetn(ctrl_intf.arst_n)
  );

  uart_if tx_intf ();
  uart_if rx_intf ();

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // VARIABLES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  integer pass_count;
  integer fail_count;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // CLASSES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  mailbox #(apb_seq_item) apb_dvr_mbx;
  mailbox #(apb_rsp_item) apb_mon_mbx;

  apb_driver apb_dvr;
  apb_monitor apb_mon;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // RTL
  //////////////////////////////////////////////////////////////////////////////////////////////////

  apb_uart_top #(
      .ADDR_WIDTH  (32),
      .DATA_WIDTH  (32),
      .WSTRB_WIDTH (4),
      .FIFO_DEPTH_W(9)
  ) DUT (
      .clk_i    (ctrl_intf.clk),
      .arst_ni  (ctrl_intf.arst_n),
      .psel_i   (apb_intf.psel),
      .penable_i(apb_intf.penable),
      .paddr_i  (apb_intf.paddr),
      .pwrite_i (apb_intf.pwrite),
      .pwdata_i (apb_intf.pwdata),
      .pstrb_i  (apb_intf.pstrb),
      .pready_o (apb_intf.pready),
      .prdata_o (apb_intf.prdata),
      .pslverr_o(apb_intf.pslverr),
      .tx_o     (tx_intf.line),
      .rx_i     (rx_intf.line),
      .intr_o   (  /*LEFT BLANK*/)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // DECLARATIONS
    ////////////////////////////////////////////////////////////////////////////////////////////////

    automatic string test_name;
    automatic int    test_repeats;

    pass_count = 0;
    fail_count = 0;

    if (!$value$plusargs("CLI_TEST_NAME=%s", test_name)) test_name = "reset_test";
    if (!$value$plusargs("CLI_TEST_REPEATS=%d", test_repeats)) test_repeats = 1;

    $dumpfile("apb_uart_top_layered_tb.vcd");
    $timeformat(-9, 0, "ns");
    $dumpvars(0, apb_uart_top_layered_tb);

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // BUILD PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    apb_dvr_mbx = new(1);
    apb_mon_mbx = new();
    apb_dvr = new();
    apb_mon = new();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // CONNECT PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    apb_dvr.set_interface(apb_intf);
    apb_mon.set_interface(apb_intf);
    apb_dvr.set_mailbox(apb_dvr_mbx);
    apb_mon.set_mailbox(apb_mon_mbx);

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // RESET PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ctrl_intf.apply_reset();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // RUN PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ctrl_intf.start_clock();

    apb_dvr.run();
    apb_mon.run();

    repeat (3) begin
      automatic apb_seq_item seq_item = new();
      seq_item.randomize() with {
        // seq_item.addr == ADDR_CTRL;
        seq_item.we == 1;
      };
      $display("apb_dvr sending: %s", seq_item.to_string());
      apb_dvr_mbx.put(seq_item);
    end

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // SHUTDOWN PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    apb_intf.wait_till_idle();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // REPORT PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    while (apb_mon_mbx.num()) begin
      apb_rsp_item item;
      apb_mon_mbx.get(item);
      $display("apb_mon received: %s", item.to_string());
    end

    #100ns;

    $finish;
  end

endmodule
