`include "ltb/obj/apb_seq_item.sv"
`include "ltb/obj/apb_rsp_item.sv"
`include "ltb/obj/uart_seq_item.sv"
`include "ltb/obj/uart_rsp_item.sv"

`include "ltb/cmp/apb_driver.sv"
`include "ltb/cmp/apb_monitor.sv"
`include "ltb/cmp/uart_driver.sv"
`include "ltb/cmp/uart_monitor.sv"

`include "ltb/cmp/generator.sv"
`include "ltb/cmp/scoreboard.sv"


module apb_uart_top_layered_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // IMPORTS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  import uart_regif_pkg::ADDR_CTRL;
  import uart_regif_pkg::ADDR_CFG;
  import uart_regif_pkg::ADDR_STATUS;
  import uart_regif_pkg::ADDR_TXD;
  import uart_regif_pkg::ADDR_RXD;
  import uart_regif_pkg::ADDR_INTR;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  ctrl_if ctrl_intf ();

  apb_if apb_intf (
      .pclk(ctrl_intf.clk),
      .presetn(ctrl_intf.arst_n)
  );

  uart_if tx_intf ();
  uart_if rx_intf ();

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // VARIABLES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  integer pass_count;
  integer fail_count;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // CLASSES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  mailbox #(apb_seq_item)  apb_dvr_mbx;
  mailbox #(apb_rsp_item)  apb_mon_mbx;

  mailbox #(uart_seq_item) uart_dvr_mbx;
  mailbox #(uart_rsp_item) uart_mon_mbx;

  generator gen;

  apb_driver apb_dvr;
  apb_monitor apb_mon;

  uart_driver uart_dvr;
  uart_monitor uart_mon;

  scoreboard scbd;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // RTL
  //////////////////////////////////////////////////////////////////////////////////////////////////

  apb_uart_top #(
      .ADDR_WIDTH  (32),
      .DATA_WIDTH  (32),
      .WSTRB_WIDTH (4),
      .FIFO_DEPTH_W(9)
  ) DUT (
      .clk_i    (ctrl_intf.clk),
      .arst_ni  (ctrl_intf.arst_n),
      .psel_i   (apb_intf.psel),
      .penable_i(apb_intf.penable),
      .paddr_i  (apb_intf.paddr),
      .pwrite_i (apb_intf.pwrite),
      .pwdata_i (apb_intf.pwdata),
      .pstrb_i  (apb_intf.pstrb),
      .pready_o (apb_intf.pready),
      .prdata_o (apb_intf.prdata),
      .pslverr_o(apb_intf.pslverr),
      .tx_o     (tx_intf.line),
      .rx_i     (rx_intf.line),
      .intr_o   (  /*LEFT BLANK*/)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // DECLARATIONS
    ////////////////////////////////////////////////////////////////////////////////////////////////

    automatic string       test_name;
    automatic int          test_repeats;
    automatic int          baud_div;
    automatic logic [31:0] cfg_data;

    pass_count = 0;
    fail_count = 0;

    if (!$value$plusargs("CLI_TEST_NAME=%s", test_name)) test_name = "reset_test";
    if (!$value$plusargs("CLI_TEST_REPEATS=%d", test_repeats)) test_repeats = 1;

    $dumpfile("apb_uart_top_layered_tb.vcd");
    $timeformat(-9, 0, "ns");
    $dumpvars(0, apb_uart_top_layered_tb);

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // BUILD PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    apb_dvr_mbx  = new(1);
    apb_mon_mbx  = new();

    uart_dvr_mbx = new(1);
    uart_mon_mbx = new();

    gen = new();

    apb_dvr = new();
    apb_mon = new();

    uart_dvr = new();
    uart_mon = new();

    scbd = new();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // CONNECT PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    gen.set_apb_mailbox(apb_dvr_mbx);
    gen.set_uart_mailbox(uart_dvr_mbx);

    apb_dvr.set_interface(apb_intf);
    apb_mon.set_interface(apb_intf);
    apb_dvr.set_mailbox(apb_dvr_mbx);
    apb_mon.set_mailbox(apb_mon_mbx);

    uart_dvr.set_interface(rx_intf);
    uart_mon.set_interface(tx_intf);
    uart_dvr.set_mailbox(uart_dvr_mbx);
    uart_mon.set_mailbox(uart_mon_mbx);

    scbd.set_apb_mailbox(apb_mon_mbx);
    scbd.set_uart_mailbox(uart_mon_mbx);
    scbd.set_interface(tx_intf);

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // RESET PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ctrl_intf.apply_reset();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // RUN PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ctrl_intf.start_clock();

    apb_dvr.run();
    apb_mon.run();

    tx_intf.baud_rate = 115200;

    uart_dvr.run();
    uart_mon.run();

    scbd.run();

    $display("\nAPB UART LAYERED TESTBENCH\n");

    baud_div = 100_000_000 / 115200;

    cfg_data = '0;
    cfg_data[15:0]  = baud_div;
    cfg_data[17:16] = 2'd3;
    cfg_data[18]    = 1'b0;
    cfg_data[19]    = 1'b0;
    cfg_data[20]    = 1'b0;

    gen.apb_write(
        ADDR_CFG,
        cfg_data
    );

    gen.apb_write(
        ADDR_CTRL,
        32'h0000_0003
    );

    apb_intf.wait_till_idle();

    repeat (10) begin
      gen.random_uart_tx();
    end

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // SHUTDOWN PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    apb_intf.wait_till_idle();

    #5ms;

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // REPORT PHASE
    ////////////////////////////////////////////////////////////////////////////////////////////////

    scbd.report();

    #100ns;

    $finish;

  end

endmodule